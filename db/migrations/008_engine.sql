-- =====================================================================
-- Apex Trader :: 007_engine.sql
-- THE MATCHING ENGINE.
--
-- This is what separates Apex Trader from a trading app that forwards
-- orders to somebody else's API. The order book lives in this database
-- and orders are crossed here, in PL/pgSQL, under a continuous-auction
-- model with PRICE-TIME PRIORITY:
--
--   1. better-priced orders execute first
--   2. among equal prices, the order that arrived first executes first
--
-- The resting (maker) order sets the execution price, so an aggressor
-- that crosses the spread receives price improvement -- exactly as on a
-- real venue.
--
-- Concurrency: matching for one instrument is serialised with a
-- TRANSACTION-SCOPED ADVISORY LOCK keyed on instrument_id. Different
-- instruments match in parallel; the same instrument never double-fills
-- a resting order. Contra rows are additionally taken FOR UPDATE.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Tunable parameters as data, not literals buried in code.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ops.config (
    key         TEXT PRIMARY KEY,
    value       NUMERIC NOT NULL,
    description TEXT NOT NULL
);

INSERT INTO ops.config (key, value, description) VALUES
 ('taker_fee_bps',        10.0, 'Fee in basis points charged to the aggressing side'),
 ('maker_fee_bps',         2.0, 'Fee in basis points charged to the resting side'),
 ('max_match_iterations', 200,  'Safety bound on fills generated by one incoming order'),
 ('max_stop_cascade',       5,  'How many rounds of stop-order election one trade may chain')
ON CONFLICT (key) DO NOTHING;

CREATE OR REPLACE FUNCTION ops.cfg(p_key TEXT)
RETURNS NUMERIC LANGUAGE sql STABLE STRICT AS $$
    SELECT value FROM ops.config WHERE key = p_key;
$$;

-- ---------------------------------------------------------------------
-- Effective limit price of an order *as the engine sees it right now*.
--
-- A stop order that has been elected behaves as a market order; an
-- elected stop-limit behaves as a limit order. Rather than mutating the
-- order's `kind` (which would break the order-shape CHECK constraint),
-- the engine derives behaviour from kind + stop_armed. NULL means
-- "market -- accept any price".
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION engine.effective_limit(o trading.trade_order)
RETURNS NUMERIC LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE o.kind
             WHEN 'market'        THEN NULL
             WHEN 'stop'          THEN NULL
             WHEN 'trailing_stop' THEN NULL
             ELSE o.limit_price
           END;
$$;

-- ---------------------------------------------------------------------
-- Order validation: microstructure rules read from the instrument master.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION engine.validate_order(
    p_instrument_id INTEGER, p_qty qty_amt, p_price_raw NUMERIC,
    p_side trading.order_side
) RETURNS TEXT LANGUAGE plpgsql STABLE AS $$
DECLARE
    v_i reference.instrument;
    v_q market.quote;
    v_band_low NUMERIC; v_band_high NUMERIC; v_ref NUMERIC;
    p_price NUMERIC;
BEGIN
    -- Normalise to the scale the price columns actually store (8 dp).
    --
    -- This matters more than it looks. A client that sends a BINARY
    -- FLOAT for a price delivers 174.729999999999989768... , because
    -- 174.73 is not representable in base 2. The value is stored
    -- correctly (NUMERIC(20,8) rounds it), but a tick-size check run on
    -- the raw parameter would compute mod(174.7299999..., 0.01) <> 0 and
    -- reject a perfectly valid price. Validating at the stored scale
    -- makes the check agree with the storage.
    --
    -- The real fix is upstream -- clients must send decimals, not floats
    -- -- and the API layer enforces that. This is the backstop.
    p_price := round(p_price_raw, 8);
    SELECT * INTO v_i FROM reference.instrument WHERE instrument_id = p_instrument_id;
    IF NOT FOUND              THEN RETURN 'unknown_instrument'; END IF;
    IF NOT v_i.is_tradable    THEN RETURN 'instrument_not_tradable'; END IF;

    -- Quantity must be a whole multiple of the lot size.
    IF mod(p_qty, v_i.lot_size) <> 0 THEN
        RETURN format('quantity must be a multiple of lot size %s', v_i.lot_size);
    END IF;

    IF p_price IS NOT NULL THEN
        -- Price must sit on the tick grid. Sub-tick prices are how you
        -- get a book that cannot be displayed or matched consistently.
        IF mod(p_price, v_i.tick_size) <> 0 THEN
            RETURN format('price must be a multiple of tick size %s', v_i.tick_size);
        END IF;

        -- PRICE BANDS (circuit-breaker style): reject orders priced far
        -- away from the reference, which is how fat-finger errors and
        -- spoofing attempts get in.
        SELECT * INTO v_q FROM market.quote WHERE instrument_id = p_instrument_id;
        v_ref := COALESCE(v_q.reference_price, v_q.last_price, v_q.prev_close);
        IF v_ref IS NOT NULL THEN
            v_band_low  := v_ref * (1 - v_i.price_band_pct/100.0);
            v_band_high := v_ref * (1 + v_i.price_band_pct/100.0);
            IF p_price < v_band_low OR p_price > v_band_high THEN
                RETURN format('price %s outside %s%% band [%s, %s]',
                              p_price, v_i.price_band_pct,
                              round(v_band_low,4), round(v_band_high,4));
            END IF;
        END IF;
    END IF;

    -- An active trading halt blocks all new orders in the instrument.
    IF EXISTS (SELECT 1 FROM risk.trading_halt h
                WHERE h.instrument_id = p_instrument_id
                  AND h.halted_until > now()) THEN
        RETURN 'instrument_halted';
    END IF;

    RETURN NULL;   -- NULL == valid
END;
$$;

-- ---------------------------------------------------------------------
-- SETTLEMENT :: turn one match into an execution + a balanced ledger
-- entry. This is where the matching engine meets the book of record.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION engine.settle_fill(
    p_instrument_id  INTEGER,
    p_buy_order_id   BIGINT,
    p_sell_order_id  BIGINT,
    p_price          price_amt,
    p_qty            qty_amt,
    p_aggressor      trading.order_side
) RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE
    v_buy_acct   BIGINT;
    v_sell_acct  BIGINT;
    v_notional   money_amt;
    v_buy_fee    money_amt;
    v_sell_fee   money_amt;
    v_entry_id   BIGINT;
    v_exec_id    BIGINT;
    v_fees_acct  BIGINT;
    v_legs       ledger.leg[];
BEGIN
    SELECT account_id INTO v_buy_acct  FROM trading.trade_order WHERE order_id = p_buy_order_id;
    SELECT account_id INTO v_sell_acct FROM trading.trade_order WHERE order_id = p_sell_order_id;
    SELECT account_id INTO v_fees_acct FROM trading.account WHERE system_code = 'HOUSE_FEES';

    v_notional := round(p_price * p_qty, 8);

    -- Asymmetric fees: the side that crossed the spread pays the taker
    -- rate, the side that provided liquidity pays the (lower) maker rate.
    v_buy_fee  := round(v_notional * (CASE WHEN p_aggressor = 'buy'
                        THEN ops.cfg('taker_fee_bps') ELSE ops.cfg('maker_fee_bps') END)/10000.0, 8);
    v_sell_fee := round(v_notional * (CASE WHEN p_aggressor = 'sell'
                        THEN ops.cfg('taker_fee_bps') ELSE ops.cfg('maker_fee_bps') END)/10000.0, 8);

    -- ---- The double-entry legs ----------------------------------
    -- cash:     -(notional+buyfee) + (notional-sellfee) + (buyfee+sellfee) = 0
    -- security: +qty (buyer) + -qty (seller)                               = 0
    v_legs := ARRAY[
        ROW(v_buy_acct,  'cash',     NULL,            -(v_notional + v_buy_fee), 'buy consideration + fee')::ledger.leg,
        ROW(v_sell_acct, 'cash',     NULL,             (v_notional - v_sell_fee),'sell proceeds - fee')::ledger.leg,
        ROW(v_buy_acct,  'security', p_instrument_id,  p_qty,                    'shares received')::ledger.leg,
        ROW(v_sell_acct, 'security', p_instrument_id, -p_qty,                    'shares delivered')::ledger.leg
    ];
    IF (v_buy_fee + v_sell_fee) > 0 THEN
        v_legs := v_legs || ROW(v_fees_acct, 'cash', NULL,
                                (v_buy_fee + v_sell_fee), 'commission revenue')::ledger.leg;
    END IF;

    v_entry_id := ledger.post_entry(
        'trade_settlement',
        format('%s x %s @ %s', p_qty, (SELECT symbol FROM reference.instrument
                                        WHERE instrument_id = p_instrument_id), p_price),
        v_legs, 'execution', NULL);

    INSERT INTO trading.execution
        (instrument_id, price, quantity, buy_order_id, sell_order_id,
         buy_account_id, sell_account_id, aggressor_side,
         buy_fee, sell_fee, settlement_entry_id)
    VALUES
        (p_instrument_id, p_price, p_qty, p_buy_order_id, p_sell_order_id,
         v_buy_acct, v_sell_acct, p_aggressor, v_buy_fee, v_sell_fee, v_entry_id)
    RETURNING execution_id INTO v_exec_id;

    -- Advance both orders. avg_fill_price is recomputed as a true
    -- volume-weighted average across every fill the order has received.
    UPDATE trading.trade_order o SET
        filled_qty     = o.filled_qty + p_qty,
        avg_fill_price = round(((COALESCE(o.avg_fill_price,0) * o.filled_qty)
                                + p_price * p_qty) / (o.filled_qty + p_qty), 8),
        status         = CASE WHEN o.filled_qty + p_qty >= o.quantity
                              THEN 'filled'::trading.order_status
                              ELSE 'partially_filled'::trading.order_status END,
        updated_at     = now()
     WHERE o.order_id IN (p_buy_order_id, p_sell_order_id);

    -- Cost-basis read model for both counterparties.
    PERFORM trading.apply_fill_to_position(v_buy_acct,  p_instrument_id,  p_qty, p_price);
    PERFORM trading.apply_fill_to_position(v_sell_acct, p_instrument_id, -p_qty, p_price);

    -- The fill is a public print: it hits the tape and the live quote.
    INSERT INTO market.tick (instrument_id, ts, price, volume, source)
    VALUES (p_instrument_id, now(), p_price, p_qty, 'internal');

    INSERT INTO market.quote AS q (instrument_id, last_price, last_size, day_volume,
                                   day_open, day_high, day_low, updated_at)
    VALUES (p_instrument_id, p_price, p_qty, p_qty, p_price, p_price, p_price, now())
    ON CONFLICT (instrument_id) DO UPDATE SET
        last_price = p_price,
        last_size  = p_qty,
        day_volume = q.day_volume + p_qty,
        day_open   = COALESCE(q.day_open, p_price),
        day_high   = GREATEST(COALESCE(q.day_high, p_price), p_price),
        day_low    = LEAST(COALESCE(q.day_low, p_price), p_price),
        updated_at = now();

    -- Real-time fan-out to WebSocket clients. LISTEN/NOTIFY means the
    -- API never polls for fills; PostgreSQL pushes them.
    PERFORM pg_notify('apex_events', json_build_object(
        'type','execution', 'instrument_id', p_instrument_id,
        'execution_id', v_exec_id, 'price', p_price, 'qty', p_qty,
        'aggressor', p_aggressor, 'ts', now()
    )::text);

    RETURN v_exec_id;
END;
$$;

-- ---------------------------------------------------------------------
-- Recompute top-of-book from resting orders and publish it.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION engine.refresh_top_of_book(p_instrument_id INTEGER)
RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE
    v_bid NUMERIC; v_bid_sz money_amt; v_ask NUMERIC; v_ask_sz money_amt;
BEGIN
    SELECT o.limit_price, sum(o.leaves_qty) INTO v_bid, v_bid_sz
      FROM trading.trade_order o
     WHERE o.instrument_id = p_instrument_id AND o.side='buy'
       AND o.status IN ('working','partially_filled') AND NOT o.stop_armed
       AND o.limit_price IS NOT NULL
     GROUP BY o.limit_price ORDER BY o.limit_price DESC LIMIT 1;

    SELECT o.limit_price, sum(o.leaves_qty) INTO v_ask, v_ask_sz
      FROM trading.trade_order o
     WHERE o.instrument_id = p_instrument_id AND o.side='sell'
       AND o.status IN ('working','partially_filled') AND NOT o.stop_armed
       AND o.limit_price IS NOT NULL
     GROUP BY o.limit_price ORDER BY o.limit_price ASC LIMIT 1;

    INSERT INTO market.quote AS q (instrument_id, bid, bid_size, ask, ask_size, updated_at)
    VALUES (p_instrument_id, v_bid, COALESCE(v_bid_sz,0), v_ask, COALESCE(v_ask_sz,0), now())
    ON CONFLICT (instrument_id) DO UPDATE SET
        bid = v_bid, bid_size = COALESCE(v_bid_sz,0),
        ask = v_ask, ask_size = COALESCE(v_ask_sz,0), updated_at = now();

    PERFORM pg_notify('apex_events', json_build_object(
        'type','book', 'instrument_id', p_instrument_id,
        'bid', v_bid, 'bid_size', v_bid_sz, 'ask', v_ask, 'ask_size', v_ask_sz
    )::text);
END;
$$;

-- =====================================================================
-- THE MATCH LOOP
-- Walks the contra side in price-time priority, filling until the
-- incoming order is exhausted or no acceptable price remains.
-- =====================================================================
CREATE OR REPLACE FUNCTION engine.match_order(p_order_id BIGINT)
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE
    v_o        trading.trade_order;
    v_limit    NUMERIC;
    v_contra   RECORD;
    v_fill_qty money_amt;
    v_fills    INTEGER := 0;
    v_guard    INTEGER := 0;
    v_max      INTEGER := ops.cfg('max_match_iterations')::int;
BEGIN
    SELECT * INTO v_o FROM trading.trade_order WHERE order_id = p_order_id FOR UPDATE;
    v_limit := engine.effective_limit(v_o);

    LOOP
        v_guard := v_guard + 1;
        EXIT WHEN v_guard > v_max;

        SELECT * INTO v_o FROM trading.trade_order WHERE order_id = p_order_id;
        EXIT WHEN v_o.leaves_qty <= 0;

        -- ---- Find the single best contra order -------------------
        -- The ORDER BY here *is* price-time priority, and it is served
        -- directly by ix_book_bids / ix_book_asks with no sort step.
        -- SKIP LOCKED is deliberately NOT used: skipping a locked order
        -- would violate time priority by letting a later order jump the
        -- queue, so we block and preserve fairness instead.
        IF v_o.side = 'buy' THEN
            SELECT c.order_id, c.limit_price, c.leaves_qty, c.account_id
              INTO v_contra
              FROM trading.trade_order c
             WHERE c.instrument_id = v_o.instrument_id
               AND c.side = 'sell'
               AND c.status IN ('working','partially_filled')
               AND NOT c.stop_armed
               AND c.limit_price IS NOT NULL
               AND c.leaves_qty > 0
               AND (v_limit IS NULL OR c.limit_price <= v_limit)
             ORDER BY c.limit_price ASC, c.seq_no ASC
             LIMIT 1
             FOR UPDATE;
        ELSE
            SELECT c.order_id, c.limit_price, c.leaves_qty, c.account_id
              INTO v_contra
              FROM trading.trade_order c
             WHERE c.instrument_id = v_o.instrument_id
               AND c.side = 'buy'
               AND c.status IN ('working','partially_filled')
               AND NOT c.stop_armed
               AND c.limit_price IS NOT NULL
               AND c.leaves_qty > 0
               AND (v_limit IS NULL OR c.limit_price >= v_limit)
             ORDER BY c.limit_price DESC, c.seq_no ASC
             LIMIT 1
             FOR UPDATE;
        END IF;

        EXIT WHEN NOT FOUND;

        v_fill_qty := least(v_o.leaves_qty, v_contra.leaves_qty);
        EXIT WHEN v_fill_qty <= 0;

        -- The RESTING order names the price. The aggressor therefore
        -- gets filled at the maker's price or better -- price
        -- improvement, not just "the price I asked for".
        PERFORM engine.settle_fill(
            v_o.instrument_id,
            CASE WHEN v_o.side='buy' THEN v_o.order_id ELSE v_contra.order_id END,
            CASE WHEN v_o.side='buy' THEN v_contra.order_id ELSE v_o.order_id END,
            v_contra.limit_price, v_fill_qty, v_o.side);

        v_fills := v_fills + 1;
    END LOOP;

    RETURN v_fills;
END;
$$;

-- =====================================================================
-- STOP-ORDER ELECTION
-- After every print, stops whose trigger price has been touched become
-- live. Trailing stops first ratchet their high-water mark.
-- =====================================================================
CREATE OR REPLACE FUNCTION engine.elect_stops(p_instrument_id INTEGER)
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE
    v_last    NUMERIC;
    v_elected INTEGER := 0;
    v_row     RECORD;
BEGIN
    SELECT last_price INTO v_last FROM market.quote WHERE instrument_id = p_instrument_id;
    IF v_last IS NULL THEN RETURN 0; END IF;

    -- Ratchet trailing stops: the stop follows the best price reached.
    UPDATE trading.trade_order o SET
        peak_price = CASE WHEN o.side='sell' THEN GREATEST(COALESCE(o.peak_price, v_last), v_last)
                                             ELSE LEAST   (COALESCE(o.peak_price, v_last), v_last) END,
        stop_price = CASE WHEN o.side='sell'
                          THEN round(GREATEST(COALESCE(o.peak_price, v_last), v_last) * (1 - o.trail_pct/100.0), 8)
                          ELSE round(LEAST   (COALESCE(o.peak_price, v_last), v_last) * (1 + o.trail_pct/100.0), 8) END
     WHERE o.instrument_id = p_instrument_id
       AND o.kind = 'trailing_stop'
       AND o.stop_armed
       AND o.status IN ('working','partially_filled');

    -- Elect every stop the last print has touched.
    FOR v_row IN
        SELECT o.order_id FROM trading.trade_order o
         WHERE o.instrument_id = p_instrument_id
           AND o.stop_armed
           AND o.status IN ('working','partially_filled')
           AND ((o.side = 'buy'  AND v_last >= o.stop_price)
             OR (o.side = 'sell' AND v_last <= o.stop_price))
         ORDER BY o.seq_no
    LOOP
        UPDATE trading.trade_order SET stop_armed = FALSE, updated_at = now()
         WHERE order_id = v_row.order_id;

        PERFORM pg_notify('apex_events', json_build_object(
            'type','stop_elected','order_id',v_row.order_id,
            'instrument_id',p_instrument_id,'trigger_price',v_last)::text);

        PERFORM engine.match_order(v_row.order_id);

        -- An elected stop that behaves as a market order must not rest.
        UPDATE trading.trade_order SET
            status = 'cancelled', updated_at = now()
         WHERE order_id = v_row.order_id
           AND leaves_qty > 0
           AND kind IN ('stop','trailing_stop');

        v_elected := v_elected + 1;
    END LOOP;

    RETURN v_elected;
END;
$$;

-- =====================================================================
-- PUBLIC ENTRY POINT :: submit an order.
-- Validation -> risk -> book -> match -> stop cascade, atomically.
-- =====================================================================
CREATE OR REPLACE FUNCTION engine.submit_order(
    p_account_id      BIGINT,
    p_instrument_id   INTEGER,
    p_side            trading.order_side,
    p_kind            trading.order_kind,
    p_quantity        qty_amt,
    p_limit_price     NUMERIC     DEFAULT NULL,
    p_stop_price      NUMERIC     DEFAULT NULL,
    p_tif             trading.time_in_force DEFAULT 'day',
    p_trail_pct       NUMERIC     DEFAULT NULL,
    p_display_qty     NUMERIC     DEFAULT NULL,
    p_client_order_id UUID        DEFAULT NULL,
    p_strategy_id     BIGINT      DEFAULT NULL,
    p_parent_order_id BIGINT      DEFAULT NULL
) RETURNS TABLE (order_id BIGINT, status trading.order_status,
                 filled_qty NUMERIC, avg_fill_price NUMERIC, reject_reason TEXT)
LANGUAGE plpgsql AS $$
DECLARE
    v_order_id   BIGINT;
    v_err        TEXT;
    v_is_stop    BOOLEAN;
    v_available  money_amt;
    v_cascade    INTEGER := 0;
    v_max_casc   INTEGER := ops.cfg('max_stop_cascade')::int;
    v_existing   BIGINT;
BEGIN
    -- ---- Idempotency ------------------------------------------------
    -- A client that retries after a timeout must not create a duplicate
    -- order. Same key in, same order out.
    IF p_client_order_id IS NOT NULL THEN
        SELECT o.order_id INTO v_existing FROM trading.trade_order o
         WHERE o.client_order_id = p_client_order_id;
        IF FOUND THEN
            RETURN QUERY SELECT o.order_id, o.status, o.filled_qty::NUMERIC, o.avg_fill_price::NUMERIC, o.reject_reason
                           FROM trading.trade_order o WHERE o.order_id = v_existing;
            RETURN;
        END IF;
    END IF;

    -- ---- Serialise matching for this instrument ---------------------
    -- Transaction-scoped: released automatically at COMMIT/ROLLBACK, so
    -- a crashed session cannot wedge the book. Keyed per instrument so
    -- unrelated symbols still match concurrently.
    PERFORM pg_advisory_xact_lock(hashtext('apex_book'), p_instrument_id);

    v_is_stop := p_kind IN ('stop','stop_limit','trailing_stop');

    -- Same normalisation on the way in, for the same reason.
    p_limit_price := round(p_limit_price, 8);
    p_stop_price  := round(p_stop_price,  8);

    INSERT INTO trading.trade_order
        (account_id, instrument_id, side, kind, tif, quantity, limit_price,
         stop_price, trail_pct, display_qty, client_order_id,
         source_strategy_id, parent_order_id, status, stop_armed,
         expires_at)
    VALUES
        (p_account_id, p_instrument_id, p_side, p_kind, p_tif, p_quantity, p_limit_price,
         p_stop_price, p_trail_pct, p_display_qty, COALESCE(p_client_order_id, gen_random_uuid()),
         p_strategy_id, p_parent_order_id, 'pending_new', v_is_stop,
         CASE WHEN p_tif = 'day' THEN date_trunc('day', now()) + INTERVAL '1 day' END)
    RETURNING trade_order.order_id INTO v_order_id;

    -- ---- Validation + pre-trade risk --------------------------------
    v_err := engine.validate_order(p_instrument_id, p_quantity,
                                   COALESCE(p_limit_price, p_stop_price), p_side);
    IF v_err IS NULL THEN
        v_err := risk.pretrade_check(p_account_id, p_instrument_id, p_side,
                                     p_quantity, COALESCE(p_limit_price, p_stop_price));
    END IF;

    IF v_err IS NOT NULL THEN
        UPDATE trading.trade_order o SET status='rejected', reject_reason=v_err, updated_at=now()
         WHERE o.order_id = v_order_id;
        RETURN QUERY SELECT o.order_id, o.status, o.filled_qty::NUMERIC, o.avg_fill_price::NUMERIC, o.reject_reason
                       FROM trading.trade_order o WHERE o.order_id = v_order_id;
        RETURN;
    END IF;

    UPDATE trading.trade_order o SET status='working', updated_at=now()
     WHERE o.order_id = v_order_id;

    -- An un-elected stop just waits; it is not on the book yet.
    IF v_is_stop THEN
        PERFORM pg_notify('apex_events', json_build_object(
            'type','order_accepted','order_id',v_order_id,
            'instrument_id',p_instrument_id,'resting',false,'armed',true)::text);
        RETURN QUERY SELECT o.order_id, o.status, o.filled_qty::NUMERIC, o.avg_fill_price::NUMERIC, o.reject_reason
                       FROM trading.trade_order o WHERE o.order_id = v_order_id;
        RETURN;
    END IF;

    -- ---- FILL-OR-KILL pre-check -------------------------------------
    -- FOK must fill completely or not at all, so the engine measures
    -- available liquidity at acceptable prices BEFORE touching the book.
    IF p_tif = 'fok' THEN
        SELECT COALESCE(sum(c.leaves_qty),0) INTO v_available
          FROM trading.trade_order c
         WHERE c.instrument_id = p_instrument_id
           AND c.side = CASE WHEN p_side='buy' THEN 'sell' ELSE 'buy' END::trading.order_side
           AND c.status IN ('working','partially_filled')
           AND NOT c.stop_armed AND c.limit_price IS NOT NULL
           AND (p_limit_price IS NULL
                OR (p_side='buy'  AND c.limit_price <= p_limit_price)
                OR (p_side='sell' AND c.limit_price >= p_limit_price));

        IF v_available < p_quantity THEN
            UPDATE trading.trade_order o
               SET status='cancelled', reject_reason=NULL, updated_at=now()
             WHERE o.order_id = v_order_id;
            RETURN QUERY SELECT o.order_id, o.status, o.filled_qty::NUMERIC, o.avg_fill_price::NUMERIC,
                                'fill_or_kill_insufficient_liquidity'::TEXT
                           FROM trading.trade_order o WHERE o.order_id = v_order_id;
            RETURN;
        END IF;
    END IF;

    -- ---- Cross the book --------------------------------------------
    PERFORM engine.match_order(v_order_id);

    -- ---- Residual handling by order type / time-in-force -----------
    -- market and IOC orders never rest; a limit order's remainder does.
    UPDATE trading.trade_order o SET status='cancelled', updated_at=now()
     WHERE o.order_id = v_order_id
       AND o.leaves_qty > 0
       AND (o.kind = 'market' OR o.tif IN ('ioc','fok'));

    PERFORM engine.refresh_top_of_book(p_instrument_id);

    -- ---- Stop cascade ----------------------------------------------
    -- Our prints may have touched resting stops, whose own fills may
    -- touch further stops. Bounded to stop a runaway chain.
    WHILE v_cascade < v_max_casc LOOP
        EXIT WHEN engine.elect_stops(p_instrument_id) = 0;
        v_cascade := v_cascade + 1;
        PERFORM engine.refresh_top_of_book(p_instrument_id);
    END LOOP;

    RETURN QUERY SELECT o.order_id, o.status, o.filled_qty::NUMERIC, o.avg_fill_price::NUMERIC, o.reject_reason
                   FROM trading.trade_order o WHERE o.order_id = v_order_id;
END;
$$;

COMMENT ON FUNCTION engine.submit_order IS
  'Atomic order entry: idempotency check, instrument advisory lock, '
  'validation, pre-trade risk, FOK liquidity probe, price-time-priority '
  'matching, residual handling per TIF, and bounded stop-order cascade. '
  'Either the whole thing commits or none of it does.';

-- ---------------------------------------------------------------------
-- Cancel / amend
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION engine.cancel_order(p_order_id BIGINT, p_account_id BIGINT DEFAULT NULL)
RETURNS trading.order_status LANGUAGE plpgsql AS $$
DECLARE v_o trading.trade_order;
BEGIN
    SELECT * INTO v_o FROM trading.trade_order WHERE order_id = p_order_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'order % not found', p_order_id USING ERRCODE='P0002'; END IF;

    IF p_account_id IS NOT NULL AND v_o.account_id <> p_account_id THEN
        RAISE EXCEPTION 'order % does not belong to account %', p_order_id, p_account_id
              USING ERRCODE='42501';
    END IF;

    IF v_o.status NOT IN ('working','partially_filled','pending_new') THEN
        RAISE EXCEPTION 'order % is % and cannot be cancelled', p_order_id, v_o.status
              USING ERRCODE='22023';
    END IF;

    PERFORM pg_advisory_xact_lock(hashtext('apex_book'), v_o.instrument_id);

    UPDATE trading.trade_order SET status='cancelled', updated_at=now() WHERE order_id = p_order_id;
    PERFORM engine.refresh_top_of_book(v_o.instrument_id);
    PERFORM pg_notify('apex_events', json_build_object(
        'type','order_cancelled','order_id',p_order_id,
        'instrument_id',v_o.instrument_id)::text);

    RETURN 'cancelled';
END;
$$;

-- Expire DAY orders at session close. Run by the maintenance job.
CREATE OR REPLACE FUNCTION engine.expire_orders()
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE v_n INTEGER;
BEGIN
    WITH expired AS (
        UPDATE trading.trade_order o SET status='expired', updated_at=now()
         WHERE o.status IN ('working','partially_filled')
           AND o.expires_at IS NOT NULL AND o.expires_at <= now()
        RETURNING o.instrument_id
    )
    SELECT count(*) INTO v_n FROM expired;
    RETURN v_n;
END;
$$;
